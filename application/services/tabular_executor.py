"""
Tabular Executor Service.
Coordinates:
- Concise schema prompting with column aliases, dtypes, sample values, min/max.
- Entity linking integration into prompt instructions.
- Relevant few-shot retrieval (top-3, prioritizing source='verified').
- Dual-engine execution via SecureCodeExecutor (DuckDB SQL primary, Pandas fallback).
- Rigorous Self-Correction Loop (up to 3 retries) with specific triggers:
  1. Exception (syntax, binder error, KeyError, timeout) -> sends last traceback + valid columns.
  2. 0 rows result -> checks if filter values were verified; if not, suggests closest catalog values.
  3. All NULL/NaN result or NULL aggregation -> suggests type casting or filter check.
  4. Missing aggregation / excessive rows when aggregation requested -> suggests GROUP BY / aggregate functions.
  5. Early stopping on duplicate code.
"""

from __future__ import annotations

import asyncio
import logging
import re
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd
import unidecode
from pydantic import BaseModel, Field

from application.interfaces.code_executor import CodeExecutor
from application.interfaces.llm_client import LLMClient
from application.services.entity_linker import normalize_entity_text
from domain.entities.entity_link import EntityLinkResult

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Structured Output Schemas
# ---------------------------------------------------------------------------

class GeneratedCodeOutput(BaseModel):
    """Structured code output generated by LLM for tabular execution."""
    language: str = Field(..., description="Target language: 'sql' (DuckDB) or 'python' (Pandas)")
    code: str = Field(..., description="Clean executable DuckDB SQL or Python code (assigning 'result')")
    explanation: str = Field(..., description="Short explanation in Vietnamese (1-2 sentences)")


class TabularExecutionResult(BaseModel):
    """Result of tabular query execution and self-correction loop."""
    success: bool = Field(..., description="True if execution succeeded with valid data")
    data: Optional[List[Dict[str, Any]]] = Field(default=None, description="Result rows as list of dicts")
    columns: List[str] = Field(default_factory=list, description="Result column names")
    row_count: int = Field(default=0, description="Number of rows returned")
    language: str = Field(default="sql", description="Language executed: 'sql' or 'python'")
    code: str = Field(default="", description="Final executed code")
    explanation: str = Field(default="", description="Explanation of query logic")
    error: Optional[str] = Field(default=None, description="Error message if execution failed")
    retries_used: int = Field(default=0, description="Number of self-correction retries attempted")


# ---------------------------------------------------------------------------
# Tabular Executor Implementation
# ---------------------------------------------------------------------------

class TabularExecutor:
    """
    Orchestrates Tabular execution with DuckDB / Pandas sandboxing
    and intelligent self-correction retry loop.
    """

    def __init__(
        self,
        llm_client: LLMClient,
        code_executor: CodeExecutor,
        max_retries: int = 3,
    ):
        self.llm_client = llm_client
        self.code_executor = code_executor
        self.max_retries = max_retries

    async def execute_query(
        self,
        query: str,
        candidate_tables: List[Dict[str, Any]],
        entity_links: Optional[List[EntityLinkResult]] = None,
        fewshot_examples: Optional[List[Dict[str, Any]]] = None,
        max_rows: int = 10000,
    ) -> TabularExecutionResult:
        """
        Generates and executes tabular queries with the Self-Correction retry loop.

        Args:
            query: User's rewritten question.
            candidate_tables: Top candidate tables with schemas and parquet file paths.
            entity_links: Resolved entity mentions to database column values.
            fewshot_examples: Relevant few-shot examples from fewshot_examples catalog.
            max_rows: Maximum rows allowed in result.

        Returns:
            TabularExecutionResult structured object.
        """
        entity_links = entity_links or []
        fewshot_examples = fewshot_examples or []

        # Prepare parquet table mapping
        table_parquet_mapping: Dict[str, str] = {}
        table_dfs: Dict[str, pd.DataFrame] = {}

        for table in candidate_tables:
            t_name = table.get("table_alias") or table.get("table_name") or table.get("name", "table_data")
            p_path = table.get("parquet_path")
            if p_path:
                table_parquet_mapping[t_name] = p_path
                clean_name = unidecode.unidecode(str(t_name))
                safe_alias = re.sub(r"[^a-zA-Z0-9_]+", "_", clean_name).strip("_").lower()
                if not safe_alias or safe_alias[0].isdigit():
                    safe_alias = f"tbl_{safe_alias}"
                table_parquet_mapping[safe_alias] = p_path
                if table.get("id"):
                    table_parquet_mapping[table["id"]] = p_path

        # Build initial prompt context
        schema_prompt = self._format_schema_prompt(candidate_tables)
        entity_prompt = self._format_entity_links_prompt(entity_links)
        fewshot_prompt = self._format_fewshot_prompt(fewshot_examples)

        system_prompt = (
            "Bạn là chuyên gia phân tích dữ liệu và sinh mã truy vấn cấp doanh nghiệp.\n"
            "Nhiệm vụ: Chuyển câu hỏi người dùng thành mã truy vấn DuckDB SQL (hoặc Python Pandas khi SQL không thực hiện được).\n"
            "QUY TẮC BẮT BUỘC:\n"
            "1. ƯU TIÊN TUYỆT ĐỐI DuckDB SQL ('sql'). Chỉ dùng Python ('python') khi bài toán yêu cầu thống kê ma trận nâng cao.\n"
            "2. Khi dùng SQL: CHỈ sinh một câu lệnh SELECT hoặc WITH duy nhất. Luôn dùng tên bảng trong dấu ngoặc kép (ví dụ: FROM \"ten_bang\").\n"
            "3. CHỈ sử dụng các cột đã được liệt kê trong schema. TUYỆT ĐỐI KHÔNG tự bịa tên cột.\n"
            "4. Khi lọc theo thực thể, bắt buộc sử dụng đúng tên cột và giá trị chuẩn hóa đã qua Entity Linking.\n"
            "5. Nếu dùng Python: Code phải gán kết quả cuối cùng vào biến `result`. Không import ngoài pandas, numpy, math, statistics, datetime.\n"
            "6. Trả về kết quả JSON theo định dạng GeneratedCodeOutput."
        )

        user_prompt = (
            f"Thông tin cấu trúc bảng biểu (Schema):\n{schema_prompt}\n\n"
            f"{entity_prompt}\n"
            f"{fewshot_prompt}\n"
            f"Câu hỏi của người dùng: \"{query}\"\n"
        )

        history_feedback: List[str] = []
        previous_code: Optional[str] = None
        retries_used = 0

        for attempt in range(self.max_retries + 1):
            # If this is a retry, append feedback to prompt
            current_prompt = user_prompt
            if history_feedback:
                current_prompt += "\nLịch sử sửa lỗi các lần thử trước:\n" + "\n".join(history_feedback)
                current_prompt += "\nHãy phân tích kỹ nguyên nhân lỗi trên và viết lại code mới để khắc phục."

            # 1. Generate code via LLM
            try:
                gen_output = await self.llm_client.structured_output(
                    prompt=current_prompt,
                    response_model=GeneratedCodeOutput,
                    system_prompt=system_prompt,
                    temperature=0.0,
                )
            except Exception as e:
                logger.warning("LLM code generation failed on attempt %d: %s", attempt, e)
                # Fallback heuristic SQL if LLM fails
                gen_output = self._fallback_sql_generation(query, candidate_tables)

            current_code = gen_output.code.strip()
            current_lang = gen_output.language.lower().strip()
            explanation = gen_output.explanation

            # Early stopping check: if new code matches previous code
            if previous_code is not None and current_code == previous_code:
                logger.info("Early stopping: generated code is identical to previous attempt.")
                return TabularExecutionResult(
                    success=False,
                    language=current_lang,
                    code=current_code,
                    explanation=explanation,
                    error="Đã dừng sớm do mô hình sinh ra mã truy vấn trùng lặp với lần thử trước.",
                    retries_used=retries_used,
                )

            previous_code = current_code

            # 2. Execute Code via SecureCodeExecutor
            success = False
            result_df: Optional[pd.DataFrame] = None
            error_msg: Optional[str] = None

            if current_lang == "python":
                # Load parquet once per file and assign aliases and default 'df'
                loaded_by_path: Dict[str, pd.DataFrame] = {}
                for t_name, p_path in table_parquet_mapping.items():
                    if t_name not in table_dfs:
                        try:
                            if p_path not in loaded_by_path:
                                loaded_by_path[p_path] = pd.read_parquet(p_path)
                            table_dfs[t_name] = loaded_by_path[p_path]
                        except Exception as e:
                            logger.warning("Failed to load DataFrame for %s: %s", t_name, e)
                if loaded_by_path and "df" not in table_dfs:
                    table_dfs["df"] = next(iter(loaded_by_path.values()))

                success, result_df, error_msg = await asyncio.to_thread(
                    self.code_executor.execute_pandas,
                    code=current_code,
                    dataframes=table_dfs,
                    timeout_seconds=15,
                    max_ram_mb=512,
                )
            else:
                current_lang = "sql"
                success, result_df, error_msg = await asyncio.to_thread(
                    self.code_executor.execute_sql,
                    query=current_code,
                    table_parquet_mapping=table_parquet_mapping,
                    max_rows=max_rows,
                )

            # 3. Check Self-Correction Triggers

            # Trigger 1: Exception (syntax error, binder error, KeyError, timeout, AST check)
            if not success or error_msg:
                retries_used += 1
                if attempt >= self.max_retries:
                    break

                tb_last_20 = "\n".join(str(error_msg).split("\n")[-20:])
                valid_cols_summary = self._get_valid_columns_summary(candidate_tables)
                feedback = (
                    f"[Lần thử {attempt + 1}] Lỗi thực thi ({current_lang}):\n"
                    f"{tb_last_20}\n"
                    f"Danh sách các cột hợp lệ và kiểu dữ liệu:\n{valid_cols_summary}"
                )
                history_feedback.append(feedback)
                continue

            # Ensure DataFrame is valid
            if result_df is None:
                result_df = pd.DataFrame()

            # Trigger 2: 0 Rows Result
            if len(result_df) == 0:
                # Check if all filter values were verified via entity linking
                all_filters_verified = self._are_all_filter_values_verified(current_code, entity_links)

                if all_filters_verified:
                    # Legitimate 0 rows result
                    logger.info("0 rows returned with verified entity filters. Returning valid empty result.")
                    return TabularExecutionResult(
                        success=True,
                        data=[],
                        columns=list(result_df.columns),
                        row_count=0,
                        language=current_lang,
                        code=current_code,
                        explanation="Không có dữ liệu khớp điều kiện tra cứu.",
                        retries_used=retries_used,
                    )
                else:
                    retries_used += 1
                    if attempt >= self.max_retries:
                        break

                    # Suggest closest distinct values
                    suggestions_str = self._get_distinct_values_suggestions(candidate_tables)
                    feedback = (
                        f"[Lần thử {attempt + 1}] Truy vấn trả về 0 dòng kết quả. "
                        f"Giá trị lọc trong câu truy vấn có thể chưa chính xác hoặc không tồn tại trong cơ sở dữ liệu.\n"
                        f"Gợi ý các giá trị phân biệt thực tế có trong bảng:\n{suggestions_str}\n"
                        f"Hãy điều chỉnh lại điều kiện lọc (WHERE) theo các giá trị thực tế trên."
                    )
                    history_feedback.append(feedback)
                    continue

            # Trigger 3: All NULL/NaN result or NULL aggregation
            if self._is_all_null_or_nan(result_df):
                retries_used += 1
                if attempt >= self.max_retries:
                    break

                feedback = (
                    f"[Lần thử {attempt + 1}] Kết quả truy vấn trả về toàn giá trị NULL hoặc NaN. "
                    f"Gợi ý: Kiểm tra kiểu dữ liệu của cột cần tính toán (nếu là chuỗi, hãy CAST sang kiểu số DECIMAL/INTEGER), "
                    f"hoặc kiểm tra lại phép toán JOIN / điều kiện lọc."
                )
                history_feedback.append(feedback)
                continue

            # Trigger 4: Missing aggregation / excessive rows when aggregation requested
            if self._is_missing_aggregation(query, current_code, result_df):
                retries_used += 1
                if attempt >= self.max_retries:
                    break

                feedback = (
                    f"[Lần thử {attempt + 1}] Câu hỏi yêu cầu tổng hợp số liệu (tổng, trung bình, cao nhất, v.v.), "
                    f"nhưng truy vấn trả về {len(result_df)} dòng dữ liệu chi tiết mà không có GROUP BY hoặc hàm tổng hợp (SUM, AVG, COUNT, MAX, MIN). "
                    f"Hãy bổ sung hàm tổng hợp hoặc mệnh đề GROUP BY phù hợp."
                )
                history_feedback.append(feedback)
                continue

            # All checks passed! Return successful execution
            rows_data = result_df.to_dict(orient="records")
            # Convert non-serializable types in rows
            clean_rows = self._clean_rows_for_json(rows_data)

            return TabularExecutionResult(
                success=True,
                data=clean_rows,
                columns=list(result_df.columns),
                row_count=len(result_df),
                language=current_lang,
                code=current_code,
                explanation=explanation,
                retries_used=retries_used,
            )

        # Exhausted all retries without success
        logger.warning("Tabular execution exhausted max retries (%d).", self.max_retries)
        last_code = previous_code or ""
        apology_msg = (
            f"Đã thử tối đa {self.max_retries} lần tự sửa lỗi nhưng truy vấn chưa thành công. "
            f"Rất xin lỗi vì sự bất tiện này. Bạn có thể diễn đạt lại câu hỏi rõ hơn không?\n"
            f"Truy vấn cuối cùng đã thử ({current_lang}):\n{last_code}"
        )

        return TabularExecutionResult(
            success=False,
            language=current_lang,
            code=last_code,
            explanation="",
            error=apology_msg,
            retries_used=retries_used,
        )

    # -----------------------------------------------------------------------
    # Helper Validation & Prompt Formatting Methods
    # -----------------------------------------------------------------------

    def _format_schema_prompt(self, candidate_tables: List[Dict[str, Any]]) -> str:
        """Formats concise schema with aliases, dtypes, samples, min/max."""
        lines = []
        for t in candidate_tables:
            t_name = t.get("table_alias") or t.get("table_name") or t.get("name", "data_table")
            desc = t.get("description", "")
            lines.append(f"Bảng: \"{t_name}\" ({desc})")
            lines.append("Cột dữ liệu:")

            cols = t.get("columns", [])
            for c in cols:
                if isinstance(c, dict):
                    col_alias = c.get("column_alias") or c.get("column_name")
                    col_name = c.get("column_name")
                    dtype = c.get("dtype", "string")
                    samples = c.get("sample_values") or []
                    samples_str = f" [Mẫu: {', '.join(str(s) for s in samples[:3])}]" if samples else ""
                    lines.append(f"  - \"{col_alias}\" (gốc: {col_name}, kiểu: {dtype}){samples_str}")
                elif isinstance(c, str):
                    lines.append(f"  - \"{c}\"")
            lines.append("")
        return "\n".join(lines)

    def _format_entity_links_prompt(self, entity_links: List[EntityLinkResult]) -> str:
        """Formats entity linking instructions."""
        if not entity_links:
            return ""

        lines = ["Kết quả phân giải thực thể (Entity Linking - Bắt buộc áp dụng):"]
        for el in entity_links:
            if el.method != "unlinked" and el.score > 0.0:
                lines.append(
                    f"- Từ khóa trong câu hỏi '{el.mention}' liên kết với cột '{el.column}' "
                    f"có giá trị chuẩn xác trong CSDL: '{el.value}' (phương pháp: {el.method})."
                )
        lines.append("")
        return "\n".join(lines)

    def _format_fewshot_prompt(self, fewshot_examples: List[Dict[str, Any]]) -> str:
        """Formats top-3 relevant few-shot examples."""
        if not fewshot_examples:
            return ""

        # Prioritize verified source
        sorted_examples = sorted(
            fewshot_examples,
            key=lambda x: 0 if x.get("source") == "verified" else 1,
        )

        lines = ["Ví dụ mẫu tương tự (Few-shot Examples):"]
        for ex in sorted_examples[:3]:
            q = ex.get("question", "")
            sql = ex.get("sql_query", "")
            src = ex.get("source", "synthetic")
            lines.append(f"- Câu hỏi: \"{q}\" (Nguồn: {src})")
            lines.append(f"  SQL: {sql}")
        lines.append("")
        return "\n".join(lines)

    def _get_valid_columns_summary(self, candidate_tables: List[Dict[str, Any]]) -> str:
        """Summarizes valid column names for feedback."""
        lines = []
        for t in candidate_tables:
            t_name = t.get("table_alias") or t.get("table_name") or t.get("name", "")
            col_list = []
            for c in t.get("columns", []):
                if isinstance(c, dict):
                    col_list.append(f"{c.get('column_alias', c.get('column_name'))} ({c.get('dtype', 'text')})")
                elif isinstance(c, str):
                    col_list.append(c)
            lines.append(f"- Bảng \"{t_name}\": {', '.join(col_list)}")
        return "\n".join(lines)

    def _get_distinct_values_suggestions(self, candidate_tables: List[Dict[str, Any]]) -> str:
        """Extracts sample distinct values from candidate tables for feedback."""
        suggestions = []
        for t in candidate_tables:
            for c in t.get("columns", []):
                if isinstance(c, dict) and c.get("sample_values"):
                    col_name = c.get("column_alias", c.get("column_name"))
                    vals = ", ".join(f"'{v}'" for v in c["sample_values"][:4])
                    suggestions.append(f"- Cột '{col_name}': {vals}")
        return "\n".join(suggestions[:5]) if suggestions else "(Không có mẫu giá trị)"

    def _are_all_filter_values_verified(
        self,
        code: str,
        entity_links: List[EntityLinkResult],
    ) -> bool:
        """
        Trigger 2 verification: Checks if filter conditions in query
        correspond to verified entity links.
        """
        if not entity_links:
            # If there are string literal comparisons in a WHERE clause without any entity link verification,
            # treat as unverified so Self-Correction can suggest actual distinct values.
            if re.search(r"\bWHERE\b.*(=|LIKE|ILIKE|IN)\s*\(?['\"]", code, re.IGNORECASE | re.DOTALL):
                return False
            return True

        # Check unlinked entities
        unlinked = [el for el in entity_links if el.method == "unlinked" or el.score < 0.7]
        if unlinked:
            return False

        # Ensure linked canonical values are actually present in the generated code
        for el in entity_links:
            if el.value and el.value not in code:
                return False

        return True

    def _is_all_null_or_nan(self, df: pd.DataFrame) -> bool:
        """Trigger 3 verification: Checks if all values in DataFrame are null/NaN."""
        if df.empty:
            return False
        # If all elements across all columns are null/NaN
        return bool(df.isna().all().all())

    def _is_missing_aggregation(self, query: str, code: str, df: pd.DataFrame) -> bool:
        """
        Trigger 4 verification: Checks if query has aggregation intent
        but code lacks GROUP BY / aggregate functions or returned > 100 raw rows.
        """
        norm_q = normalize_entity_text(query)
        agg_keywords = ["tong", "tong cong", "trung binh", "cao nhat", "thap nhat", "dem", "so luong"]
        has_agg_intent = any(kw in norm_q for kw in agg_keywords)

        if not has_agg_intent:
            return False

        norm_code = code.upper()
        has_agg_function = any(fn in norm_code for fn in ["SUM(", "AVG(", "COUNT(", "MAX(", "MIN(", "GROUP BY"])

        # If user asked for aggregation but query returned > 500 rows and lacks agg functions
        if not has_agg_function and len(df) > 50:
            return True

        return False

    def _clean_rows_for_json(self, rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """Converts dates, timestamps, NaNs in rows to JSON-serializable types."""
        clean = []
        for r in rows:
            clean_row = {}
            for k, v in r.items():
                if pd.isna(v):
                    clean_row[k] = None
                elif hasattr(v, "isoformat"):
                    clean_row[k] = v.isoformat()
                else:
                    clean_row[k] = v
            clean.append(clean_row)
        return clean

    def _fallback_sql_generation(
        self,
        query: str,
        candidate_tables: List[Dict[str, Any]],
    ) -> GeneratedCodeOutput:
        """Deterministic fallback SQL generation if LLM fails."""
        if not candidate_tables:
            return GeneratedCodeOutput(
                language="sql",
                code="SELECT 1 as result;",
                explanation="Truy vấn mặc định.",
            )
        t_name = candidate_tables[0].get("table_alias") or candidate_tables[0].get("table_name", "data_table")
        return GeneratedCodeOutput(
            language="sql",
            code=f'SELECT * FROM "{t_name}" LIMIT 10;',
            explanation=f'Truy vấn mẫu 10 dòng đầu tiên của bảng {t_name}.',
        )
